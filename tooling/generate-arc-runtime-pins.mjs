/** Exact reviewed Arc V2 runtimes, with only the canonical constructor immutables patched. */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { keccak256 } from "viem";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const trustedForwarder = "0x7dE7A249673F2235A91E484CfCE49D00867B67Ec";
const token = "0xAe77D247c26258397653a020995E957Bc88E039A";
const identities = {};

for (const kind of ["Swap", "Staking", "Lending"]) {
  const name = `KletiaArc${kind}V2`;
  const artifactDir = resolve(root, "contracts/arc/artifacts/contracts", `${name}.sol`);
  const debug = JSON.parse(readFileSync(resolve(artifactDir, `${name}.dbg.json`), "utf8"));
  const build = JSON.parse(readFileSync(resolve(artifactDir, debug.buildInfo), "utf8"));
  const compiled = build.output.contracts[`contracts/${name}.sol`][name].evm.deployedBytecode;
  const expected = kind === "Staking" ? ["_trustedForwarder"] : ["_trustedForwarder", kind === "Swap" ? "token" : "kletToken"];
  const names = new Map();
  const walk = (node) => {
    if (Array.isArray(node)) return node.forEach(walk);
    if (!node || typeof node !== "object") return;
    if (node.nodeType === "VariableDeclaration" && node.mutability === "immutable") names.set(String(node.id), node.name);
    for (const value of Object.values(node)) walk(value);
  };
  for (const source of Object.values(build.output.sources)) walk(source.ast);
  let runtime = compiled.object;
  const patched = [];
  for (const [id, references] of Object.entries(compiled.immutableReferences)) {
    const immutableName = names.get(id);
    if (!expected.includes(immutableName)) throw new Error(`${name}: unexpected immutable ${immutableName ?? id}`);
    patched.push(immutableName);
    const address = immutableName === "_trustedForwarder" ? trustedForwarder : token;
    for (const { start, length } of references) {
      if (length !== 32) throw new Error(`${name}: unsupported immutable length ${length}`);
      const value = address.slice(2).toLowerCase().padStart(length * 2, "0");
      runtime = runtime.slice(0, start * 2) + value + runtime.slice((start + length) * 2);
    }
  }
  if (patched.length !== expected.length || !expected.every((value) => patched.includes(value))) throw new Error(`${name}: expected immutable references missing`);
  identities[kind.toLowerCase()] = { contract: name, runtimeCodehash: keccak256(`0x${runtime}`), runtimeBytes: runtime.length / 2 };
}

const output = `/** Generated by tooling/generate-arc-runtime-pins.mjs; compile Arc before checking. */\nexport const ARC_REVIEWED_V2_RUNTIMES = ${JSON.stringify(identities, null, 2)} as const;\n\nexport const ARC_REVIEWED_FORWARDER = "${trustedForwarder}";\nexport const ARC_REVIEWED_TOKEN = "${token}";\n`;
const destination = resolve(root, "apps/api/src/networks/arc/reviewedRuntimePins.ts");
if (check) {
  if (readFileSync(destination, "utf8") !== output) throw new Error("Reviewed Arc V2 runtime pins drifted; compile and regenerate them for review.");
  console.log("Reviewed Arc V2 runtime pins match compiled source.");
} else {
  writeFileSync(destination, output);
  console.log("Generated reviewed Arc V2 runtime pins; no deployed address or funded execution is implied.");
}
